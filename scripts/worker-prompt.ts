import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { askSystem } from '../src/ai/ask.js';

// Compile the Ask prompt files into a module the Worker can import (Workers can't read files),
// with the same version hash the eval reports, so you can see they match.
const system = askSystem(await readFile('prompts/ask.md', 'utf8'), await readFile('prompts/graph-schema.md', 'utf8'));
const version = createHash('sha1').update(system).digest('hex').slice(0, 10);
const summary = await readFile('prompts/summary.md', 'utf8');
await writeFile(
  'worker/src/prompt.generated.ts',
  `// Generated by \`npm run worker:prompt\` from prompts/ask.md and prompts/graph-schema.md. Do not edit.\n` +
    `export const PROMPT_VERSION = ${JSON.stringify(version)};\nexport const SYSTEM = ${JSON.stringify(system)};\n` +
    `export const SUMMARY_SYSTEM = ${JSON.stringify(summary)};\n`,
);
console.log(`worker/src/prompt.generated.ts: prompt ${version}`);
